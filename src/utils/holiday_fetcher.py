"""Fetch NSE trading holidays from the official API and emit `config/holidays.yaml`.

NSE exposes `/api/holiday-master?type=trading` which returns the same list as the
PDF circular. Run once at the start of each calendar year, or whenever NSE
issues a mid-year amendment.

Usage:
    python -m src.utils.holiday_fetcher                # current year, prints YAML
    python -m src.utils.holiday_fetcher --write        # also overwrite config/holidays.yaml
    python -m src.utils.holiday_fetcher --year 2027    # specify year
"""
from __future__ import annotations

import argparse
import sys
from datetime import date, datetime
from pathlib import Path
from typing import Any

import yaml
from loguru import logger

from ..session import NSESession
from .config import CONFIG_DIR, get_endpoints


# Fallback if the API shape changes — fill manually from
# https://www.nseindia.com/resources/exchange-communication-holidays
_HOLIDAY_ENDPOINT = "https://www.nseindia.com/api/holiday-master?type=trading"


def _parse_date(s: str) -> date | None:
    for fmt in ("%d-%b-%Y", "%Y-%m-%d", "%d-%m-%Y", "%d/%m/%Y"):
        try:
            return datetime.strptime(s.strip(), fmt).date()
        except ValueError:
            continue
    return None


def fetch_holidays(year: int) -> list[dict[str, Any]]:
    """Return list of {date, name} dicts for the given year."""
    # Allow override from endpoints.yaml if user added it later.
    url = (
        get_endpoints().get("mvp", {}).get("holiday_master")
        or _HOLIDAY_ENDPOINT
    )
    session = NSESession()
    try:
        raw = session.get(url)
    finally:
        session.close()

    # Response: { "CM": [ {tradingDate, weekDay, description}, ... ], "FO": [...], ... }
    segments = ["CM", "FO", "CD", "CO", "MCXSXCD"]
    seen: dict[date, str] = {}
    for seg in segments:
        for item in raw.get(seg, []):
            d = _parse_date(item.get("tradingDate", ""))
            if d is None or d.year != year:
                continue
            name = (item.get("description") or "").strip()
            seen.setdefault(d, name or "Holiday")

    rows = [{"date": d.isoformat(), "name": n} for d, n in sorted(seen.items())]
    return rows


def emit_yaml(year: int, rows: list[dict[str, Any]]) -> str:
    doc = {
        "year": year,
        "trading_holidays": [
            {"date": r["date"], "name": r["name"]} for r in rows
        ],
    }
    header = (
        "# NSE Trading Holidays\n"
        "# Source of truth: https://www.nseindia.com/resources/exchange-communication-holidays\n"
        "# Auto-generated by src/utils/holiday_fetcher.py. Edit by hand only for amendments.\n\n"
    )
    return header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True)


def cli() -> None:
    p = argparse.ArgumentParser(description="Fetch NSE trading holidays from the official API.")
    p.add_argument("--year", type=int, default=date.today().year, help="Calendar year (default: this year)")
    p.add_argument("--write", action="store_true", help="Overwrite config/holidays.yaml")
    args = p.parse_args()

    try:
        rows = fetch_holidays(args.year)
    except Exception as e:
        logger.error("Holiday fetch failed: {}", e)
        sys.exit(1)

    if not rows:
        logger.error("No holidays returned for {}", args.year)
        sys.exit(2)

    yaml_text = emit_yaml(args.year, rows)
    if args.write:
        path = Path(CONFIG_DIR) / "holidays.yaml"
        path.write_text(yaml_text, encoding="utf-8")
        logger.info("Wrote {} holidays to {}", len(rows), path)
    else:
        sys.stdout.write(yaml_text)


if __name__ == "__main__":
    cli()
